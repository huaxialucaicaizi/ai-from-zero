#!/usr/bin/env python3
"""Build dist/single-file/<skill>.md from SKILL.md + references/ (fixed order)."""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "dist" / "single-file"

# Skills without scripts: paste-ready single files.
PASTE_SKILLS = [
    "ai-sources",
    "ai-for-my-job",
    "prompt-coach",
    "skill-maker",
]


def build_one(name: str) -> Path:
    skill_dir = ROOT / name
    skill_md = skill_dir / "SKILL.md"
    parts: list[str] = []
    header = (
        f"<!-- ai-from-zero single-file: {name} "
        f"(SKILL.md + references/, generated by CI; do not edit by hand) -->\n\n"
    )
    parts.append(header)
    parts.append(skill_md.read_text(encoding="utf-8").rstrip() + "\n")

    refs = skill_dir / "references"
    if refs.exists():
        for path in sorted(refs.glob("*.md")):
            parts.append("\n---\n\n")
            parts.append(f"<!-- reference: references/{path.name} -->\n\n")
            parts.append(path.read_text(encoding="utf-8").rstrip() + "\n")

    # ai-sources also ships sources.md at skill root (first-party list).
    sources = skill_dir / "sources.md"
    if sources.exists():
        parts.append("\n---\n\n")
        parts.append("<!-- reference: sources.md -->\n\n")
        parts.append(sources.read_text(encoding="utf-8").rstrip() + "\n")

    OUT.mkdir(parents=True, exist_ok=True)
    out_path = OUT / f"{name}.md"
    out_path.write_text("".join(parts), encoding="utf-8")
    return out_path


def main() -> None:
    written = [build_one(name) for name in PASTE_SKILLS]
    for path in written:
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
